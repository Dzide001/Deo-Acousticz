package com.droidacoustic.pro.prediction

import com.droidacoustic.pro.acoustics.*
import com.droidacoustic.pro.geometry.BoundaryPoint
import com.droidacoustic.pro.scene.*
import kotlin.math.*
import kotlin.test.*

class AsymmetricOrientationTest {
    private val data=ClfData("asymmetric-test-only",patterns=listOf(ClfPolarPattern(1000,
        listOf(90f,0f,-90f,45f,-180f,-45f),listOf(-45f,0f,45f),
        listOf(-28f,0f,-9f,-18f,-40f,-3f).map {h->floatArrayOf(h-5,h,h-12)}.toTypedArray())),
        sensitivityDbByBand=mapOf(1000 to 93f))
    private fun source(yaw:Float,poses:List<ArrayGeometry.Pose>,steer:Float=0f)=SourceSnapshot(
        42,0f,0f,0f,yaw,poses,steer,0f,FrozenResponse.measured(data,true))
    private fun request(source:SourceSnapshot,receivers:List<ReceiverSnapshot> = emptyList())=PredictionRequest(
        PredictionTicket(1,1,PredictionChannel.COVERAGE),listOf(source),receivers,1000,listOf(1000),1f/3,emptyMap(),true,Atmosphere())

    @Test fun canonicalWorldAxesDoNotSwapSpeakerLeftAndRight() {
        val d=sqrt(50f)
        // Explicit world coordinates, not generated by the production rotation helper.
        val cases=listOf(0f to listOf(ReceiverSnapshot(d,0f,-d),ReceiverSnapshot(d,0f,d)),
            90f to listOf(ReceiverSnapshot(d,0f,d),ReceiverSnapshot(-d,0f,d)),
            -90f to listOf(ReceiverSnapshot(-d,0f,-d),ReceiverSnapshot(d,0f,-d)))
        for((yaw,receivers) in cases) {
            val output=request(source(yaw,listOf(ArrayGeometry.Pose(0f,0f,0f,0f))),receivers).calculate()
            assertEquals(15f,output.levelAt(0)-output.levelAt(1),.002f)
        }
    }

    @Test fun eachArrayElementKeepsItsOwnFrameAndSteeringCannotMirrorIt() {
        val poses=listOf(ArrayGeometry.Pose(.1f,.3f,5f,.3f),ArrayGeometry.Pose(0f,0f,15f,0f),ArrayGeometry.Pose(-.1f,-.3f,25f,-.3f))
        // Facing +Z: cabinet right is -X. A receiver at +X is therefore left.
        val receivers=listOf(AngularReceiver("left","left",BoundaryPoint(6.0,2.0,9.0)),
            AngularReceiver("right","right",BoundaryPoint(-6.0,2.0,9.0)))
        val report=request(source(90f,poses)).receiverAngularSupport(receivers)
        assertEquals(report.toJsonString(),request(source(90f,poses,20f)).receiverAngularSupport(receivers).toJsonString())
        for((i,receiver) in receivers.withIndex()) for((j,pose) in poses.withIndex()) {
            val ray=report.receivers[i].rows.single {it.elementIndex==j}
            // Independent inverse pitch, after explicitly rotating world yaw=90 degrees.
            val forward=receiver.position.z-pose.forwardM
            val up=receiver.position.y-pose.upM
            val right=-receiver.position.x
            val tilt=pose.tiltDownDeg*PI/180
            val localForward=cos(tilt)*forward-sin(tilt)*up
            val localUp=sin(tilt)*forward+cos(tilt)*up
            assertEquals((atan2(right,localForward)*180/PI).toFloat(),ray.azimuthDeg,.0001f)
            assertEquals((atan2(localUp,hypot(localForward,right))*180/PI).toFloat(),ray.elevationDeg,.0001f)
        }
    }
}
